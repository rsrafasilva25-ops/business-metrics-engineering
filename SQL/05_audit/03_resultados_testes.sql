CREATE TABLE IF NOT EXISTS audit.resultados_testes
(
    resultado_id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
    nome_teste character varying(100) COLLATE pg_catalog."default" NOT NULL,
    quantidade_falhas integer NOT NULL,
    status character varying(10) COLLATE pg_catalog."default" NOT NULL,
    executado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    execucao_id bigint,
    CONSTRAINT resultados_testes_pkey PRIMARY KEY (resultado_id),
    CONSTRAINT fk_resultados_execucoes FOREIGN KEY (execucao_id)
        REFERENCES audit.execucoes_testes (execucao_id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,
    CONSTRAINT chk_status_teste CHECK (status::text = ANY (ARRAY['PASSOU'::character varying, 'FALHOU'::character varying]::text[]))
)

TABLESPACE pg_default;

ALTER TABLE IF EXISTS audit.resultados_testes
    OWNER to postgres;